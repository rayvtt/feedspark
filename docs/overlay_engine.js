/* FeedSpark Overlays — detection engine (docs/overlay_engine.js)
 * ------------------------------------------------------------------
 * UMD, dependency-free, browser + node. Served verbatim at /overlays/engine.js,
 * required by the 4x-daily xml-scan agent (tools/xml_scan.mjs) and unit-tested in
 * node (tools/test_overlays.mjs) — every lane runs this exact file.
 *
 * What it answers (Ray, 10 Sep 2026): "when you scan the feed for each client that
 * has the overlay service on — especially the Meta feed — the image link starts with
 * dashboard.feedspark.com: render the TYPE of overlay that is live on each client and
 * render the image. The clue for the overlay type is in the URL string."
 *
 * API:
 *   Overlay.isOverlayUrl(url)        -> true when the image is served by a FeedSpark
 *                                       image service (dashboard./lia. feedspark.com,
 *                                       feed5.com)
 *   Overlay.classifyOverlay(url)     -> { key, family, project, script, label, tokens,
 *                                       recipe:[{k,label,v,url?}], sources:[url…],
 *                                       ver, layout } | null
 *   Overlay.overlayCollector(meta)   -> { onRow, finish } on the Feed Lab parser
 *                                       contract (first onRow = header, then rows;
 *                                       XML header may grow mid-stream)
 *   Overlay.VERSION
 *
 * Every figure is computed from the feed rows — nothing is hardcoded per brand. New
 * overlay scripts FeedSpark ships later classify automatically from their URL tokens
 * (the label is derived, never looked up), so an unseen overlay type is still shown,
 * never hidden.
 */
(function (root, factory) {
  var api = factory();
  try { root.Overlay = api; } catch (e) {}
  if (typeof module !== 'undefined' && module.exports) { module.exports = api; }
}(typeof globalThis !== 'undefined' ? globalThis :
  (typeof self !== 'undefined' ? self : this), function () {
  'use strict';

  var VERSION = '1.0.0';
  var SAMPLES = 16;          // rendered examples kept per overlay type per feed
  var MAX_TYPES = 40;        // distinct scripts tracked per feed (safety cap)

  // FeedSpark image services. dashboard.* hosts the image-creator scripts (the overlay
  // engines); lia.* hosts the Meta dynamic-template renderer; feed5.com is the sibling
  // domain Ray named. Any of them = the image is generated by FeedSpark, not the client CDN.
  var HOST_RE = /^https?:\/\/([a-z0-9-]+\.)?(feedspark|feed5)\.com(\/|$)/i;

  function isOverlayUrl(u) {
    return HOST_RE.test(String(u == null ? '' : u).trim());
  }

  // ---- URL string decoding -------------------------------------------------------
  // Feed URLs are XML-decoded by the parser but their query VALUES are not percent-
  // encoded (img_url=https://cdn…/x.webp?v=1772186897&width=1000): a naive split on
  // '&' would still be right here, but a source URL carrying its own '&' would be cut —
  // so a segment without '=' is glued back onto the previous value.
  function parseQuery(q) {
    var out = [], parts = String(q || '').split('&'), i, seg, eq, k, prev;
    for (i = 0; i < parts.length; i++) {
      seg = parts[i]; if (!seg) continue;
      eq = seg.indexOf('=');
      k = eq < 0 ? seg : seg.slice(0, eq);
      prev = out.length ? out[out.length - 1] : null;
      // continuation of a source URL's own query (…x.jpg?a=1&b=2): glue when the previous
      // value is a URL already carrying '?' and this key is not one the engines take
      if (prev && isUrl(prev.v) && prev.v.indexOf('?') >= 0 && (eq < 0 || !PARAM[k.toLowerCase()])) { prev.v += '&' + seg; continue; }
      if (eq < 0) { out.push({ k: seg, v: '' }); continue; }
      out.push({ k: k, v: seg.slice(eq + 1) });
    }
    return out;
  }
  var isUrl = function (v) { return /^https?:\/\//i.test(String(v || '')); };

  // token dictionary for the script / project names (image_process_products_lifestyle
  // -> Product × Lifestyle); unknown tokens are capitalised, never dropped
  var WORDS = {
    products: 'Product', product: 'Product', lifestyle: 'Lifestyle', lifestyles: 'Lifestyle',
    price: 'Price', prices: 'Price', pricing: 'Price', sale: 'Sale', sales: 'Sale', discount: 'Discount',
    badge: 'Badge', badges: 'Badge', roundel: 'Roundel', logo: 'Logo', text: 'Text', promo: 'Promo',
    banner: 'Banner', frame: 'Frame', bg: 'Background', background: 'Background', split: 'Split',
    mix: 'Mix', subscription: 'Subscription', subscribe: 'Subscription', engine: 'Dynamic engine',
    dynamic: 'Dynamic', overlay: 'Overlay', tag: 'Tag', tags: 'Tag', sticker: 'Sticker', ribbon: 'Ribbon',
    dpa: 'DPA', meta: 'Meta', catalog: 'Catalogue', catelog: 'Catalogue', catalogue: 'Catalogue',
    template: 'Template', swatch: 'Swatch', colour: 'Colour', color: 'Colour', model: 'Model',
    cutout: 'Cut-out', packshot: 'Packshot', bundle: 'Bundle', review: 'Review', rating: 'Rating',
    stars: 'Star rating', delivery: 'Delivery', shipping: 'Delivery', stock: 'Stock', new: 'New-in',
    bestseller: 'Best seller', bestsellers: 'Best seller', offer: 'Offer', offers: 'Offer'
  };
  var NOISE = { image: 1, img: 1, process: 1, call: 1, php: 1, v: 1, create: 1, creator: 1, generate: 1 };

  function tokenize(s) {
    return String(s || '').toLowerCase().split(/[^a-z0-9]+/).filter(function (t) { return t && !NOISE[t]; });
  }
  function prettyTokens(toks) {
    var out = [], i, t, m;
    for (i = 0; i < toks.length; i++) {
      t = toks[i];
      m = /^v(\d+)$/.exec(t);
      if (m) { out.push('v' + m[1]); continue; }
      if (/^\d+$/.test(t)) continue;
      out.push(WORDS[t] || (t.charAt(0).toUpperCase() + t.slice(1)));
    }
    return out;
  }

  // human readouts for the query parameters the overlay scripts take
  var PARAM = {
    img_url_left: 'Left image', img_url_right: 'Right image', img_url: 'Source image', image_url: 'Source image',
    img: 'Source image', image: 'Source image', width: 'Output width', height: 'Output height',
    img_ver: 'Version', ver: 'Engine version', image_version: 'Image version', v: 'Version',
    overlay_frame: 'Frame asset', overlay_img_pos: 'Image position', overlay_pos: 'Overlay position',
    show_price: 'Price shown', price: 'Price', sale_price: 'Sale price', discount: 'Discount',
    tags_font_color: 'Tag text colour', tags_bg_color: 'Tag background', tags_img_type: 'Tag style',
    font_color: 'Text colour', bg_color: 'Background colour', text: 'Text', label: 'Label',
    report_template_id: 'Template id', template_hash: 'Template hash', template_id: 'Template id',
    cache: 'Cached', brand: 'Brand', logo: 'Logo'
  };
  var VER_KEYS = { img_ver: 1, image_version: 1, ver: 1, v: 1 };
  var prettyKey = function (k) { return String(k).replace(/[_-]+/g, ' ').replace(/^./, function (c) { return c.toUpperCase(); }); };
  var stripExt = function (s) { return String(s).replace(/\.(php|aspx?|jsp|cgi)$/i, ''); };
  var friendlyValue = function (k, v) {
    if (/color|colour/.test(k) && /^[0-9a-f]{6}$/i.test(v)) return '#' + v.toUpperCase();
    if (k === 'overlay_frame') return stripFrame(v);
    if (k === 'tags_img_type') return prettyTokens(tokenize(v)).join(' ');
    if (k === 'cache') return v === '1' ? 'yes' : v;
    return v;
  };
  // white_1000_yumove_1_1726228743.png -> "white 1000 yumove 1" (upload stamp dropped)
  function stripFrame(v) {
    return String(v).replace(/\.(png|jpe?g|webp|gif)$/i, '').replace(/_\d{9,}$/, '').replace(/_/g, ' ');
  }

  function classifyOverlay(u) {
    var s = String(u == null ? '' : u).trim();
    if (!HOST_RE.test(s)) return null;
    var m = /^https?:\/\/([^\/?#]+)([^?#]*)(?:\?(.*))?$/i.exec(s);
    if (!m) return null;
    var host = m[1].toLowerCase(), path = m[2] || '/', query = m[3] || '';
    var segs = path.split('/').filter(Boolean);
    // a trailing slash = a bare engine directory (no script): every segment is the project
    var bare = /\/$/.test(path) || !segs.length;
    var script = bare ? '' : stripExt(segs[segs.length - 1]);
    var dirs = bare ? segs : segs.slice(0, -1);
    var family, projSegs;
    if (dirs[0] === 'image-creator') { family = 'image-creator'; projSegs = dirs.slice(1); }
    else if (/^lia\./.test(host) || /meta-dynamic/.test(dirs[0] || '')) { family = 'meta-dynamic'; projSegs = dirs.slice(1); }
    else { family = 'feedspark-hosted'; projSegs = dirs; }
    var project = projSegs.join('/');
    var params = parseQuery(query);
    var sources = [], recipe = [], seen = {}, ver = '', i, p, k;
    for (i = 0; i < params.length; i++) {
      p = params[i]; k = p.k.toLowerCase();
      if (isUrl(p.v)) { sources.push(p.v); recipe.push({ k: k, label: PARAM[k] || prettyKey(k), v: p.v, url: true }); continue; }
      if (VER_KEYS[k] && !ver) ver = p.v;
      if (seen[k]) continue;          // YuMOVE carries width twice on one URL — first wins
      seen[k] = 1;
      recipe.push({ k: k, label: PARAM[k] || prettyKey(k), v: friendlyValue(k, p.v) });
    }
    // layout = how many source images the engine composes
    var hasLR = seen.img_url_left || seen.img_url_right || /img_url_left=/.test(query);
    var layout = hasLR ? 'split' : (sources.length > 1 ? 'multi' : (sources.length === 1 ? 'single' : 'generated'));
    // label: the script name is the primary clue, the project name (minus the brand /
    // channel words) the secondary; the engine family is the fallback
    var scriptToks = tokenize(script.replace(/^image_process_?/, '').replace(/^meta_catelog_/, 'meta catalogue '));
    var brandToks = {};
    var pt = tokenize(projSegs.join(' '));
    for (i = 0; i < pt.length; i++) brandToks[pt[i]] = 1;
    var words = prettyTokens(scriptToks);
    if (family === 'image-creator' && /^dynamic-overlay-engine\b/.test(project)) {
      words = ['Dynamic overlay engine'];
      if (seen.overlay_frame) { var fr = recipe.filter(function (r) { return r.k === 'overlay_frame'; })[0]; if (fr) words.push('· frame ' + fr.v); }
    } else if (family === 'meta-dynamic') {
      words = ['Meta dynamic template'];
      var vm = /meta-dynamic-v(\d+)/i.exec(dirs.join('/')); if (vm) words.push('v' + vm[1]);
    } else if (!words.length) {
      // no script tokens (bare engine path) — fall back to the project name
      words = prettyTokens(pt.filter(function (t) { return !/^(meta|fb|google|shopping|feed|gb|uk|us|de|fr|ie)$/.test(t); }));
      if (!words.length) words = ['FeedSpark overlay'];
    }
    var label = words.join(' ');
    if (layout === 'split') label = label.replace(/ Mix$/, '').replace(/^(\w[\w-]*) (\w[\w-]*)$/, '$1 × $2') + ' split';
    if (seen.show_price && !/price/i.test(label)) label += ' · price tag';
    var key = host + path;   // stable identity of the overlay recipe (query varies per SKU)
    return { key: key, host: host, family: family, project: project, script: script, label: label,
      tokens: scriptToks, layout: layout, sources: sources, recipe: recipe, ver: ver };
  }

  // ---- feed collector ------------------------------------------------------------
  // Feed Lab parser contract: first onRow(row) = header, then one row per product;
  // the XML parser may GROW the header mid-stream (liveHeader) — re-resolve then.
  function normKey(k) {
    return String(k == null ? '' : k).replace(/^\uFEFF/, '').trim().toLowerCase().replace(/^g:/, '').replace(/\s*\|\|\|\s*(\d+)$/, '($1)');
  }
  function overlayCollector(meta) {
    meta = meta || {};
    var header = null, cols = null, rows = 0, ovl = 0, addl = 0, plain = 0;
    var hosts = {}, types = {}, order = [];
    function resolve() {
      var c = { id: -1, title: -1, link: -1, image: -1, addl: [] }, i, k;
      for (i = 0; i < header.length; i++) {
        k = normKey(header[i]);
        if (k === 'id' && c.id < 0) c.id = i;
        else if (k === 'title' && c.title < 0) c.title = i;
        else if (k === 'link' && c.link < 0) c.link = i;
        else if (k === 'image_link' && c.image < 0) c.image = i;
        else if (/^additional_image_link(\(\d+\))?$/.test(k)) c.addl.push(i);
      }
      cols = c;
    }
    function bump(url, row, where) {
      var cls = classifyOverlay(url);
      if (!cls) return null;
      var t = types[cls.key];
      if (!t) {
        if (order.length >= MAX_TYPES) return cls;
        t = types[cls.key] = { key: cls.key, host: cls.host, family: cls.family, project: cls.project, script: cls.script,
          label: cls.label, layout: cls.layout, n: 0, addl: 0, vers: {}, samples: [], recipe: cls.recipe.filter(function (r) { return !r.url; }) };
        order.push(cls.key);
      }
      if (where === 'image') t.n++; else t.addl++;
      if (cls.ver) t.vers[cls.ver] = (t.vers[cls.ver] || 0) + 1;
      if (where === 'image' && t.samples.length < SAMPLES) {
        t.samples.push({ id: cols.id >= 0 ? String(row[cols.id] == null ? '' : row[cols.id]).trim().slice(0, 80) : '',
          ti: cols.title >= 0 ? String(row[cols.title] == null ? '' : row[cols.title]).trim().slice(0, 140) : '',
          link: cols.link >= 0 ? String(row[cols.link] == null ? '' : row[cols.link]).trim().slice(0, 500) : '',
          url: String(url).trim().slice(0, 2000), src: cls.sources.slice(0, 4), ver: cls.ver });
      }
      return cls;
    }
    function onRow(r, liveHeader) {
      if (!header) { header = r; resolve(); return; }
      if (liveHeader && liveHeader.length !== header.length) { header = liveHeader.slice(); resolve(); }
      rows++;
      var im = cols.image >= 0 ? String(r[cols.image] == null ? '' : r[cols.image]).trim() : '';
      if (im) {
        if (bump(im, r, 'image')) ovl++;
        else {
          plain++;
          var hm = /^https?:\/\/([^\/?#]+)/i.exec(im);
          var h = hm ? hm[1].toLowerCase() : '(no host)';
          hosts[h] = (hosts[h] || 0) + 1;
        }
      }
      var got = false, i, v;
      for (i = 0; i < cols.addl.length; i++) {
        v = String(r[cols.addl[i]] == null ? '' : r[cols.addl[i]]).trim();
        if (v && isOverlayUrl(v)) { bump(v, r, 'addl'); got = true; }
      }
      if (got) addl++;
    }
    function finish() {
      if (!header) throw new Error('fetch-fail: no rows parsed');
      var list = order.map(function (k) { return types[k]; }).sort(function (a, b) { return (b.n + b.addl) - (a.n + a.addl); });
      var hostList = Object.keys(hosts).map(function (h) { return [h, hosts[h]]; }).sort(function (a, b) { return b[1] - a[1]; }).slice(0, 5);
      return { v: 1, t: Date.now(), client: meta.client || '', market: meta.market || '', rows: rows, ovl: ovl, addl: addl, plain: plain,
        hasImage: cols.image >= 0, hosts: hostList, types: list };
    }
    return { onRow: onRow, finish: finish };
  }

  return { VERSION: VERSION, SAMPLES: SAMPLES, isOverlayUrl: isOverlayUrl, classifyOverlay: classifyOverlay,
    overlayCollector: overlayCollector, parseQuery: parseQuery, normKey: normKey };
}));
